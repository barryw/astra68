#ifndef ASTRA_RESULT_H
#define ASTRA_RESULT_H

#include <astra/status.h>
#include <astra/syscall.h>
#include <astra/types.h>

static inline AstraResult astra_result_from_syscall(uint32_t status)
{
    switch (status) {
    case ASTRA_SYSCALL_OK: return ASTRA_OK;
    case ASTRA_SYSCALL_BAD_SYSCALL: return ASTRA_ERROR_UNSUPPORTED;
    case ASTRA_SYSCALL_INVALID_ARGUMENT: return ASTRA_ERROR_INVALID_ARGUMENT;
    case ASTRA_SYSCALL_INVALID_HANDLE: return ASTRA_ERROR_INVALID_HANDLE;
    case ASTRA_SYSCALL_ACCESS_DENIED: return ASTRA_ERROR_PERMISSION;
    case ASTRA_SYSCALL_RESOURCE_LIMIT: return ASTRA_ERROR_NO_RESOURCES;
    case ASTRA_SYSCALL_WOULD_BLOCK: return ASTRA_ERROR_WOULD_BLOCK;
    case ASTRA_SYSCALL_TIMED_OUT: return ASTRA_ERROR_TIMEOUT;
    case ASTRA_SYSCALL_PEER_DEAD: return ASTRA_ERROR_PEER_DEAD;
    case ASTRA_SYSCALL_BAD_ADDRESS: return ASTRA_ERROR_BAD_ADDRESS;
    case ASTRA_SYSCALL_CANCELLED: return ASTRA_ERROR_CANCELLED;
    case ASTRA_SYSCALL_OUT_OF_MEMORY: return ASTRA_ERROR_OUT_OF_MEMORY;
    case ASTRA_SYSCALL_IO_ERROR: return ASTRA_ERROR_IO;
    case ASTRA_SYSCALL_CLOSED: return ASTRA_ERROR_CLOSED;
    case ASTRA_SYSCALL_BUFFER_TOO_SMALL: return ASTRA_ERROR_BUFFER_TOO_SMALL;
    default: return ASTRA_ERROR_IO;
    }
}

static inline AstraResult astra_result_from_service(uint32_t status)
{
    switch (status) {
    case ASTRA_STATUS_OK: return ASTRA_OK;
    case ASTRA_STATUS_PROTOCOL:
    case ASTRA_STATUS_INVALID: return ASTRA_ERROR_INVALID_ARGUMENT;
    case ASTRA_STATUS_BAD_HANDLE:
    case ASTRA_STATUS_NOT_FOUND: return ASTRA_ERROR_INVALID_HANDLE;
    case ASTRA_STATUS_ACCESS: return ASTRA_ERROR_PERMISSION;
    case ASTRA_STATUS_LIMIT:
    case ASTRA_STATUS_NO_SPACE: return ASTRA_ERROR_NO_RESOURCES;
    case ASTRA_STATUS_UNSUPPORTED: return ASTRA_ERROR_UNSUPPORTED;
    case ASTRA_STATUS_BUSY: return ASTRA_ERROR_BUSY;
    case ASTRA_STATUS_BUFFER_TOO_SMALL: return ASTRA_ERROR_BUFFER_TOO_SMALL;
    case ASTRA_STATUS_PEER_DEAD: return ASTRA_ERROR_PEER_DEAD;
    default: return ASTRA_ERROR_IO;
    }
}

#endif
